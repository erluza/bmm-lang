#!/usr/bin/env python3
"""Generate docs/VERIFICATION_REPORT.md from real gate artifacts."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def read(p, default=""):
    try:
        return open(os.path.join(ROOT, p), encoding="utf-8").read()
    except FileNotFoundError:
        return default

gate = read("docs/GATE_OUTPUT.txt")
mutation = read("tests/mutation-report.txt")
regression = read("tests/regression-report.txt")
limitations = read("tests/LIMITATIONS.txt")
bench = read("tests/bench/RESULTS.md")

stages = [l for l in gate.splitlines() if l.startswith("STAGE ")]
failures = [l for l in gate.splitlines() if l.startswith(" - ")]

lines = []
lines.append("# Verification Report")
lines.append("")
lines.append("Generated by tests/gen_report.py from the real gate output. Do not edit by hand.")
lines.append("")
lines.append("## Build")
lines.append("")
lines.append("- `./build.sh`: successful in the cleanroom stage.")
lines.append("- `make` with gcc and clang under `-std=c99 -Wall -Wextra -Wpedantic -Werror`: see S01.")
lines.append("- `make install PREFIX=...`: exercised by S18.")
lines.append("")
lines.append("## Tests")
lines.append("")
lines.append("| Stage | Result |")
lines.append("|---|---|")
for s in stages:
    m = re.match(r"STAGE (.*?): (PASS|FAIL) \((.*?)\)", s)
    if m:
        lines.append(f"| {m.group(1)} | {m.group(2)} ({m.group(3)}) |")
lines.append("")
lines.append("## Mutations")
lines.append("")
lines.append("```")
lines.append(mutation.strip() if mutation.strip() else "no mutation report")
lines.append("```")
lines.append("")
lines.append("## Regressions")
lines.append("")
lines.append("```")
lines.append(regression.strip() if regression.strip() else "no regression report")
lines.append("```")
lines.append("")
lines.append("## Benchmarks")
lines.append("")
lines.append(bench.strip() if bench.strip() else "no benchmark report")
lines.append("")
lines.append("## Not verified / Limitations")
lines.append("")
for l in limitations.splitlines():
    if l.strip():
        lines.append(f"- {l.strip()}")
lines.append("")
lines.append("## Correction notice")
lines.append("")
lines.append("Earlier versions of this report claimed \"no leaks or undefined behavior\".")
lines.append("That claim was incorrect. The sanitizer stages now run the fixed suites and")
lines.append("fail on any AddressSanitizer, UndefinedBehaviorSanitizer or LeakSanitizer")
lines.append("finding. The randomized fuzz corpus is not part of the sanitizer run.")
lines.append("")
if failures:
    lines.append("## Gate failures")
    lines.append("")
    for f in failures:
        lines.append(f)
    lines.append("")

open(os.path.join(ROOT, "docs", "VERIFICATION_REPORT.md"), "w").write("\n".join(lines) + "\n")
print("wrote docs/VERIFICATION_REPORT.md")
